ALIASES = {
    'alert-triangle': 'warning',
    'calendar': 'calendar-blank',
    'chevron-down': 'caret-down',
    'clipboard': 'clipboard-text',
    'droplet': 'drop',
    'eye-off': 'eye-slash',
    'lock': 'lock-simple',
    'mail': 'envelope-simple',
    'menu': 'list',
    'refresh': 'arrows-clockwise',
    'search': 'magnifying-glass',
}


@register.simple_tag
def icon(name, size=None, css_class='', label='', stroke_width=None):
    body = ICONS.get(ALIASES.get(name, name))
    if body is None:
        if settings.DEBUG:
            raise template.TemplateSyntaxError(
                f'Unknown icon "{name}". Available: {", ".join(icon_names())}'
            )
        logger.warning('Unknown icon requested: %s', name)
        return ''

    classes = f'icon {css_class}'.strip()
    dimensions = f' width="{int(size)}" height="{int(size)}"' if size else ''
    if label:
        accessibility = f'role="img" aria-label="{escape(label)}"'
    else:
        accessibility = 'aria-hidden="true" focusable="false"'

    return mark_safe(
        f'<svg class="{escape(classes)}" viewBox="0 0 256 256" fill="currentColor"'
        f'{dimensions} {accessibility}>{body}</svg>'
    )


@register.simple_tag
def icon_names():
    """Every registered icon name, aliases included. Handy when auditing templates."""
    return sorted(set(ICONS) | set(ALIASES))
